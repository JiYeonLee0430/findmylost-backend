/**
 * 시/도 짧은 이름. 공공 습득물(PublicItem.region)과 같은 기준.
 * 광주·전남은 2026-07-01 전남광주통합특별시로 합쳐졌고, 공공 데이터도 '전남'으로 들어오므로
 * 저장 값은 '전남' 하나로 통일한다. (화면 표시는 프론트에서 '전남광주통합특별시')
 */
export const REGIONS = [
  '서울', '부산', '대구', '인천', '대전', '울산', '세종',
  '경기', '강원', '충북', '충남', '전북', '전남', '경북', '경남', '제주',
];

const LONG_TO_SHORT: Record<string, string> = {
  서울특별시: '서울', 부산광역시: '부산', 대구광역시: '대구', 인천광역시: '인천',
  대전광역시: '대전', 울산광역시: '울산', 세종특별자치시: '세종',
  경기도: '경기', 강원도: '강원', 강원특별자치도: '강원',
  충청북도: '충북', 충청남도: '충남',
  전라북도: '전북', 전북특별자치도: '전북',
  경상북도: '경북', 경상남도: '경남',
  제주도: '제주', 제주특별자치도: '제주',
  // 광주·전남 통합: 옛 이름, 새 이름, 줄임말을 모두 '전남'으로
  전라남도: '전남', 광주광역시: '전남', 광주: '전남',
  전남광주통합특별시: '전남', 전남광주특별시: '전남',
  전남광주: '전남', 광주전남: '전남', '광주·전남': '전남', '전남·광주': '전남',
};

/** "충청남도" → "충남", "광주" → "전남". 모르는 값은 그대로 돌려줘서 검증에서 걸리게 함 */
export function toShortRegion(value: unknown) {
  if (typeof value !== 'string') return value;
  const v = value.trim();
  return LONG_TO_SHORT[v] ?? v;
}